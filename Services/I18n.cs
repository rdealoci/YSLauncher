        public static string CurrentLang { get; private set; } = "en";
        public static event Action? LanguageChanged;
        
        public static void SetLanguage(string langCode)
        {
            CurrentLang = langCode;
            LanguageChanged?.Invoke();
        }
        
        public static void AutoDetect()
        {
            string? saved = GetSavedLanguage();
            if (!string.IsNullOrEmpty(saved))
            {
                SetLanguage(saved);
                return;
            }

            string detected = DetectSystemLanguage();
            SetLanguage(detected);
        }

        public static string DetectSystemLanguage()
        {
            try
            {
                // Linux environment variables for UI messages (POSIX standard)
                if (OperatingSystem.IsLinux())
                {
                    string[] envs = new[] { "LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG" };
                    foreach (var varName in envs)
                    {
                        string? val = Environment.GetEnvironmentVariable(varName);
                        if (!string.IsNullOrEmpty(val))
                        {
                            // Formats like en_US.UTF-8 or pt_BR or en:pt
                            string firstPart = val.Split(':')[0].Split('.')[0];
                            string prefix = firstPart.Split('_')[0].ToLowerInvariant();
                            if (Translations.ContainsKey(prefix)) return prefix;
                        }
                    }
                }

                // OS and .NET UI culture checks
                string uiLang = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
                if (Translations.ContainsKey(uiLang)) return uiLang;

                // Fallback to general culture
                string cultLang = CultureInfo.CurrentCulture.TwoLetterISOLanguageName.ToLowerInvariant();
                if (Translations.ContainsKey(cultLang)) return cultLang;
            }
            catch { }

            return "en";
        }
        
        public static string TForLang(string langCode, string key)
        {
            if (Translations.ContainsKey(langCode) && Translations[langCode].ContainsKey(key))
                return Translations[langCode][key];

            if (Translations["en"].ContainsKey(key))
                return Translations["en"][key];

            return key;
        }
        
        public static string T(string key)
        {
            if (Translations.ContainsKey(CurrentLang) && Translations[CurrentLang].ContainsKey(key))
                return Translations[CurrentLang][key];
            
            if (Translations["en"].ContainsKey(key))
                return Translations["en"][key];
                
            return key;
        }
        
        public static bool HasConfiguredLanguage => LauncherConfig.HasConfiguredLanguage;

        public static void SaveLanguage(string langCode)
        {
            LauncherConfig.Language = langCode;
        }

        public static string? GetSavedLanguage()
        {
            string? lang = LauncherConfig.Language;
            if (!string.IsNullOrEmpty(lang) && Translations.ContainsKey(lang))
                return lang;
            return null;
        }

